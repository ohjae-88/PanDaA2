/** V4 동등: 시드 → flat Skill 배열. id 형식 `sk_{skillId}` */
export function buildSeedSkills(): Skill[] {
  const out: Skill[] = [];
  for (const [jobId, list] of Object.entries(RAW)) {
    for (const s of list) {
      const baseLv = SKILL_BASELV_SEED[s.category];
      out.push({
        id: `sk_${s.id}`,
        skillId: s.id,
        name: s.name,
        category: s.category,
        icon: ICON_BASE + s.icon,
        jobId,
        job: JOB_KO[jobId] ?? jobId,
        baseLv: { base: baseLv.base, daevanion: baseLv.daevanion },
        daevanion: baseLv.daevanion > 0,
        specialEffects: [],
      });
    }
  }
  return out;
}

export const DEFAULT_SKILL_SEED = buildSeedSkills();
